// Builds src/poses.js: one representative two-hand pose per seal, used to
// draw the seal hints. Run with: node tools/make-poses.mjs samples.json
//
// For each seal it picks the medoid of the two-hand samples (the sample with
// the smallest total distance to the others), then rebuilds both hands from
// the normalised features: each hand in hand-size units around its wrist,
// the second hand placed at the stored wrist offset.
import fs from 'node:fs';
import { poseDistance } from '../src/knn.js';

const file = process.argv[2] ?? new URL('../samples/seal-samples.json', import.meta.url);
const data = JSON.parse(fs.readFileSync(file, 'utf8'));
const samples = (data.samples ?? data).filter(s => s.features[87] > 0);

const hand = (f, start, dx = 0, dy = 0) => {
  const points = [];
  for (let i = 0; i < 21; i++) points.push([+(f[start + 2 * i] + dx).toFixed(3), +(f[start + 2 * i + 1] + dy).toFixed(3)]);
  return points;
};

const poses = {};
for (const label of [...new Set(samples.map(s => s.label))].sort()) {
  const group = samples.filter(s => s.label === label);
  let best = null;
  let bestTotal = Infinity;
  for (const a of group) {
    let total = 0;
    for (const b of group) total += poseDistance(a.features, b.features);
    if (total < bestTotal) [best, bestTotal] = [a, total];
  }
  const f = best.features;
  poses[label] = [hand(f, 0), hand(f, 42, f[84], f[85])];
  console.log(label, group.length, 'two-hand samples');
}

const out = new URL('../src/poses.js', import.meta.url);
fs.writeFileSync(out, `// Generated by tools/make-poses.mjs from the bundled samples: one
// representative pose per seal, [hand, hand], each [x, y] in hand-size units.
export const POSES = ${JSON.stringify(poses)};\n`);
